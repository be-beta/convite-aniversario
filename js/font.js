// Acentos: duas linhas, desenhados acima da letra base.
const ACENTOS = {
  agudo: ['..#', '.#.'],
  grave: ['#..', '.#.'],
  circ: ['.#.', '#.#'],
  til: ['.##.#', '#.##.'],
  trema: ['#.#', '...'],
};

const COMPOSTOS = {
  'á': ['a', 'agudo'], 'à': ['a', 'grave'], 'â': ['a', 'circ'], 'ã': ['a', 'til'],
  'é': ['e', 'agudo'], 'ê': ['e', 'circ'], 'è': ['e', 'grave'],
  'ó': ['o', 'agudo'], 'ô': ['o', 'circ'], 'õ': ['o', 'til'],
  'ú': ['u', 'agudo'], 'ü': ['u', 'trema'],
  'Á': ['A', 'agudo'], 'À': ['A', 'grave'], 'Â': ['A', 'circ'], 'Ã': ['A', 'til'],
  'É': ['E', 'agudo'], 'Ê': ['E', 'circ'], 'Í': ['I', 'agudo'],
  'Ó': ['O', 'agudo'], 'Ô': ['O', 'circ'], 'Õ': ['O', 'til'], 'Ú': ['U', 'agudo'],
};

const TROCAS = { '“': '"', '”': '"', '‘': "'", '’': "'", '–': '-', '—': '-', 'ñ': 'n' };

export const LINE_H = 12; // altura de linha em pixels da fonte
const TOPO = 2; // deslocamento para caber acentos de maiúsculas

const glifos = new Map();

function compilar(rows, extra = []) {
  const px = [];
  let w = 0;
  rows.forEach((r, y) => {
    w = Math.max(w, r.length);
    for (let x = 0; x < r.length; x++) if (r[x] === '#') px.push([x, y]);
  });
  for (const p of extra) px.push(p);
  return { w, px };
}

function glifo(ch) {
  if (glifos.has(ch)) return glifos.get(ch);
  let g;
  if (ch === ' ') g = { w: 3, px: [] };
  else if (RAW[ch]) g = compilar(RAW[ch]);
  else if (COMPOSTOS[ch]) {
    const [base, ac] = COMPOSTOS[ch];
    const b = compilar(RAW[base]);
    const a = ACENTOS[ac];
    const aw = a[0].length;
    const ox = Math.max(0, Math.floor((b.w - aw) / 2));
    const oy = base === base.toUpperCase() ? -2 : 0;
    const extra = [];
    a.forEach((r, y) => { for (let x = 0; x < r.length; x++) if (r[x] === '#') extra.push([x + ox, y + oy]); });
    g = { w: Math.max(b.w, aw + ox), px: b.px.concat(extra) };
  } else if (TROCAS[ch]) g = glifo(TROCAS[ch]);
  else g = compilar(RAW['?']);
  glifos.set(ch, g);
  return g;
}

export function measure(str) {
  let w = 0;
  for (const ch of str) w += glifo(ch).w + 1;
  return Math.max(0, w - 1);
}

// Quebra o texto em linhas que caibam em maxW (em pixels da fonte).
export function wrap(str, maxW) {
  const out = [];
  for (const par of String(str).split('\n')) {
    const words = par.split(' ');
    let line = '';
    for (const word of words) {
      const test = line ? line + ' ' + word : word;
      if (measure(test) <= maxW || !line) {
        line = test;
      } else {
        out.push(line);
        line = word;
      }
    }
    out.push(line);
  }
  return out;
}

const cache = new Map();

function textCanvas(str, color, shadow) {
  const key = color + '|' + shadow + '|' + str;
  let c = cache.get(key);
  if (c) return c;
  if (cache.size > 600) cache.clear();
  const w = measure(str) + 1;
  c = document.createElement('canvas');
  c.width = Math.max(1, w);
  c.height = LINE_H;
  const g = c.getContext('2d');
  const desenhar = (cor, dx, dy) => {
    g.fillStyle = cor;
    let x = 0;
    for (const ch of str) {
      const gl = glifo(ch);
      for (const [px, py] of gl.px) g.fillRect(x + px + dx, py + TOPO + dy, 1, 1);
      x += gl.w + 1;
    }
  };
  if (shadow) desenhar(shadow, 1, 1);
  desenhar(color, 0, 0);
  cache.set(key, c);
  return c;
}

// Desenha texto. x, y em pixels do destino; s = tamanho de cada pixel da fonte.
export function drawText(ctx, str, x, y, s, color = '#f4ead2', shadow = null, align = 'left') {
  if (!str) return 0;
  const c = textCanvas(str, color, shadow);
  let dx = x;
  if (align === 'center') dx = x - Math.floor(measure(str) * s / 2);
  else if (align === 'right') dx = x - measure(str) * s;
  ctx.imageSmoothingEnabled = false;
  ctx.drawImage(c, Math.round(dx), Math.round(y), c.width * s, c.height * s);
  return measure(str) * s;
}

// Desenha texto direto no buffer de cena (escala 1).
export function drawTextPx(ctx, str, x, y, color, shadow = null) {
  return drawText(ctx, str, x, y, 1, color, shadow);
}
